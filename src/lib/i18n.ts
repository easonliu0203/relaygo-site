export type LangCode = 'zh-TW' | 'zh-CN' | 'en' | 'ja' | 'ko' | 'th' | 'vi' | 'ms' | 'id' | 'fil';

export function detectLang(): LangCode {
  if (typeof window === 'undefined') return 'en';

  const params = new URLSearchParams(window.location.search);
  const p = params.get('lang');
  if (p && I18N[p]) return p as LangCode;

  // Only use stored language if user manually selected it
  const stored = localStorage.getItem('relaygo_lang_manual');
  if (stored && I18N[stored]) return stored as LangCode;

  // Auto-detect from browser language
  const nav = (navigator.language || '').toLowerCase();
  if (nav.startsWith('ko')) return 'ko';
  if (nav.startsWith('ja')) return 'ja';
  if (nav.startsWith('th')) return 'th';
  if (nav.startsWith('vi')) return 'vi';
  if (nav.startsWith('ms') || nav.startsWith('my')) return 'ms';
  if (nav.startsWith('id')) return 'id';
  if (nav.startsWith('fil') || nav.startsWith('tl')) return 'fil';
  if (nav === 'zh-cn' || nav === 'zh-sg' || nav.startsWith('zh-hans')) return 'zh-CN';
  if (nav.startsWith('zh')) return 'zh-TW';
  return 'en';
}
